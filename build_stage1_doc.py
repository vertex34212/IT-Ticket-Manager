def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = tcPr.find(qn('w:shd'))
    if shd is None:
        shd = OxmlElement('w:shd'); tcPr.append(shd)
    shd.set(qn('w:fill'), fill)

def borders(table, color='D9D9D9', sz='6'):
    tblPr = table._tbl.tblPr
    b = tblPr.first_child_found_in('w:tblBorders')
    if b is None:
        b = OxmlElement('w:tblBorders'); tblPr.append(b)
    for edge in ('top','left','bottom','right','insideH','insideV'):
        tag = 'w:' + edge
        el = b.find(qn(tag))
        if el is None:
            el = OxmlElement(tag); b.append(el)
        el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), sz); el.set(qn('w:space'), '0'); el.set(qn('w:color'), color)

def cell_text(cell, text, bold=False, color=None, size=9.2):
    cell.text = ''
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.05
    r = p.add_run(str(text)); r.bold = bold; r.font.name='Aptos'; r.font.size=Pt(size)
    if color: r.font.color.rgb = RGBColor(*color)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER

def table(headers, rows, widths=None, font_size=9.1):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    borders(t)
    for i,h in enumerate(headers):
        shade(t.rows[0].cells[i], '334E68')
        cell_text(t.rows[0].cells[i], h, True, (255,255,255), font_size)
    hdrPr = t.rows[0]._tr.get_or_add_trPr()
    hdr = OxmlElement('w:tblHeader'); hdr.set(qn('w:val'), 'true'); hdrPr.append(hdr)
    for ridx,row in enumerate(rows):
        cells = t.add_row().cells
        trPr = t.rows[-1]._tr.get_or_add_trPr()
        trPr.append(OxmlElement('w:cantSplit'))
        for i,val in enumerate(row):
            if ridx % 2 == 1: shade(cells[i], 'F3F6F8')
            cell_text(cells[i], val, False, None, font_size)
    if widths:
        for row in t.rows:
            for i,w in enumerate(widths): row.cells[i].width = Inches(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)
    return t

def p(text='', bold_prefix=None, italic=False):
    para = doc.add_paragraph()
    if bold_prefix and text.startswith(bold_prefix):
        r=para.add_run(bold_prefix); r.bold=True
        para.add_run(text[len(bold_prefix):])
    else:
        r=para.add_run(text); r.italic=italic
    return para

def bullet(text, level=0):
    para=doc.add_paragraph(style='List Bullet' if level==0 else 'List Bullet 2')
    para.paragraph_format.space_after=Pt(3)
    para.add_run(text)
    return para

